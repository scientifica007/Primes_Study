"""Study 12 independent tests: exactness, oracle traces and adversary blocks."""
import sys
import unittest
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/"experiments"))
from layered_oracle_decision import (
    Oracle, scan_E, orbit_data, orbit_E, generator_E, hard_family, report,
)
from finite_monoids import associative, E
from green_structural_monoids import principal_ideal, unit_elements


class LayeredOracleTests(unittest.TestCase):
    def test_all_170_small_monoids(self):
        r=report()
        self.assertEqual(sum(x["monoids"] for x in r["labelled_small_monoids"]),170)
        for x in r["labelled_small_monoids"]:
            self.assertTrue(x["all_predictions_match"])
            self.assertLessEqual(x["orbit_and_Green_queries_with_precomputed_metadata"],
                                 x["nonunit_pair_bound_sum"])
            self.assertLessEqual(x["orbit_only_queries_with_precomputed_metadata"],
                                 x["nonunit_pair_bound_sum"])

    def test_adversary_requires_every_block_on_base(self):
        k=5
        n=3*k+5
        tab=hard_family(k)
        U=(0,1,2)
        prep=Oracle(tab)
        orbits=orbit_data(n,0,U,prep,unit_generators=(1,))
        self.assertEqual(prep.calls,2*(n-3))
        self.assertEqual(len(orbits[0]),k+2)
        self.assertEqual(len(orbits[1]),k+2)
        q=Oracle(tab)
        result=orbit_E(n,0,U,q,orbits)
        self.assertEqual(result["E"],[n-2])
        touched={((a-3)//3,(b-3)//3) for a,b in q.trace
                 if 3<=a<n-2 and 3<=b<n-2}
        self.assertEqual(len(touched),k*k)
        self.assertGreaterEqual(q.calls,k*k)
        self.assertLessEqual(q.calls,(k+2)**2)
        for i,j in touched:
            variant=hard_family(k,(i,j))
            self.assertEqual(E(variant,n),())
            self.assertEqual(unit_elements(variant,n,0),U)

    def test_generator_oracle_exact_with_small_generating_sets(self):
        # Monoid C_n generated by the element 1, including e as empty word.
        for n in (1,2,3,5,12):
            tab=tuple((a+b)%n for a in range(n) for b in range(n))
            q=Oracle(tab)
            X=(1,) if n>1 else ()
            self.assertEqual(generator_E(n,0,X,q),E(tab,n))
            self.assertEqual(q.calls,(n-1)*len(X))
        # C3 x 2-element meet semilattice, e is label 1.
        el=[(a,b) for a in range(3) for b in range(2)]
        tab=tuple(el.index(((a+c)%3,min(b,d))) for a,b in el for c,d in el)
        q=Oracle(tab)
        self.assertEqual(generator_E(6,1,(3,0),q),())
        self.assertEqual(q.calls,10)
        with self.assertRaises(ValueError):
            generator_E(6,1,(3,),Oracle(tab))

    def test_identity_and_singleton_not_dropped(self):
        q=Oracle((0,))
        self.assertEqual(scan_E(1,q),(0,))
        self.assertEqual(orbit_E(1,0,(0,),Oracle((0,)),((),()))["E"],[0])
        self.assertEqual(generator_E(1,0,(),Oracle((0,))),(0,))

    def test_large_units_no_fixed_nonunits_no_residual_queries(self):
        el=[(a,b) for a in range(3) for b in range(8)]
        tab=tuple(el.index(((a+c)%3,b&d)) for a,b in el for c,d in el)
        n=len(el)
        U=unit_elements(tab,n,7)
        prep=Oracle(tab)
        orbits=orbit_data(n,7,U,prep,unit_generators=(15,))
        q=Oracle(tab)
        result=orbit_E(n,7,U,q,orbits)
        self.assertEqual(result["E"],[])
        self.assertEqual(q.calls,0)
        self.assertEqual(prep.calls,42)

    def test_green_pruning_excludes_maximal_singleton(self):
        # 3-element cyclic group + absorbing zero.
        n=4
        tab=tuple((a+b)%3 if a<3 and b<3 else 3 for a in range(n) for b in range(n))
        U=(0,1,2)
        orbits=orbit_data(n,0,U,Oracle(tab))
        ideals=tuple(principal_ideal(tab,n,x) for x in range(n))
        q=Oracle(tab)
        out=orbit_E(n,0,U,q,orbits,ideals)
        self.assertEqual(out["E"],[3])
        self.assertEqual(out["forced_by_Green_singletons"],[3])
        self.assertEqual(q.calls,0)

if __name__=="__main__":
    unittest.main()
